def test_assignments_satisfy_every_stated_constraint():
    """Re-verify the solver's answer against each constraint family, in plain
    Python, the way `validateAssignments` does on the TS side.

    The two tests above leave most of the model untestable: deleting the
    participant-rest `AddNoOverlap`, the order-dependency inequality or the
    per-division day cap leaves both of them green (measured — the rest mutant
    survived them). A solver whose constraint families can be removed without
    a test noticing is the failure mode this repo has been bitten by before,
    so each family gets an assertion that fails without it.

    DO NOT TREAT THIS TEST AS THE GUARD FOR COURT GAP OR PARTICIPANT REST.
    It catches them only by luck. Measured over six runs per cell against a
    pristine mirror, with the mutation's presence verified in each run:

        mutant                                   8 s wall     3 s wall
        M2  participant-rest NoOverlap deleted   RED 5/6      RED 6/6
        M7  gap dropped from the court width     RED 1/6      RED 6/6
        baseline (unmutated)                     GREEN 2/2    GREEN 2/2

    Two things follow, and the second corrects a claim an earlier version of
    this docstring asserted as fact:

      * M7 is a **coin flip here — 1 in 6** at the shipped wall. It is now
        genuinely guarded by `test_the_court_turnaround_gap_is_binding`, and
        M2 by `test_participant_rest_is_binding`, both on purpose-built
        contended boards that decide on a proved COUNT in milliseconds.
      * A LONGER WALL MAKES THESE TWO **LESS** DETECTABLE, NOT MORE. The
        earlier claim that "T1's packing pressure is what exposes them" was
        drawn from a single run per cell and is wrong — with six runs the
        effect reverses. The real driver is that this board is uncontended:
        8 320 slots, 37 fixtures and a day cap of one per division per day
        leave everything naturally spread out, so a deleted turnaround or rest
        window usually changes no placement at all. The more tiers finish, the
        better-optimised the board, and the fewer incidental violations remain
        for this test to trip over.

    So the 8 s wall is NOT load-bearing coverage. It is kept only because it
    is what the other assertions here were measured at and nothing argues for
    changing it; if suite runtime ever needs to come down this is a legitimate
    place to take it from, provided the M1-M8 matrix is re-run to confirm the
    families it really does guard (M1, M3, M4, M5, M8) still die.
    """
    # `rule_groups` (from `_production_board()`, derived from the SAME
    # declared `rest_by_division`/`day_cap_by_division` `constraints` below
    # still carries, for computing the EXPECTED numbers this test checks the
    # board against) is what actually binds the rest/cap families now:
    # `division_rules` (proto field 10), the wire path that used to carry
    # them, is retired -- see `_board_positional.rule_groups_for`'s own
    # docstring, and `placement.schema`'s module docstring for the wire side.
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps, rule_groups = (
        _production_board()
    )
    model = build_model(
        fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps,
        rule_groups=rule_groups,
    )
    outcome = solve(model, wall_seconds=8.0)
    assert outcome.assignments, "nothing placed — the rest of this test would be vacuous"
    assert len(outcome.assignments) == len(fixtures), (
        "not every fixture was placed, so some constraint arm below may be vacuous"
    )

    dur_ms = constraints["match_minutes"] * MIN_MS
    gap_ms = constraints["gap_minutes"] * MIN_MS
    rest_by_division = constraints["rest_by_division"]
    day_cap_by_division = constraints["day_cap_by_division"]

    # Fixture identity is now POSITION, so these are lists, not id-keyed dicts.
    entrants_of = [ents for ents, _div in fixtures]
    division_of = [div for _ents, div in fixtures]
    placed = {fi: (court, start) for fi, court, start in outcome.assignments}
    legal_court_starts = {(court, start) for court, start, _day in grid_slots}

    # every placement lands on a tick THAT COURT actually offers
    for fi, (court, start) in placed.items():
        assert 0 <= court < num_courts, f"fixture {fi} placed on unknown court {court}"
        assert (court, start) in legal_court_starts, (
            f"fixture {fi} placed at {start} on court {court}, not a legal slot"
        )

    # court turnaround (match+gap), movable vs movable AND vs immovable rows
    occupancy = [(court, start, fi) for fi, (court, start) in placed.items()]
    occupancy += [(court, start, f"existing:{k}") for k, (court, start) in enumerate(existing)]
    for a in range(len(occupancy)):
        for b in range(a + 1, len(occupancy)):
            court_a, start_a, name_a = occupancy[a]
            court_b, start_b, name_b = occupancy[b]
            if court_a != court_b:
                continue
            assert abs(start_a - start_b) >= dur_ms + gap_ms, (
                f"court turnaround violated on court {court_a}: {name_a}@{start_a} vs {name_b}@{start_b}"
            )

    # participant rest: an entrant's two matches are separated by match+rest
    by_entrant = {}
    for fi, (_court, start) in placed.items():
        for entrant in entrants_of[fi]:
            by_entrant.setdefault(entrant, []).append((start, fi))
    for entrant, rows in by_entrant.items():
        rows.sort()
        for a in range(len(rows)):
            for b in range(a + 1, len(rows)):
                (start_a, fi_a), (start_b, fi_b) = rows[a], rows[b]
                need = dur_ms + rest_by_division.get(division_of[fi_a], 0) * MIN_MS
                assert start_b - start_a >= need, (
                    f"rest violated for entrant {entrant}: fixture {fi_a}@{start_a} vs "
                    f"fixture {fi_b}@{start_b}, need {need}ms"
                )

    # order dependencies: `after` starts no earlier than `before` + match + its own rest
    checked_deps = 0
    for before_i, after_i in deps:
        if before_i not in placed or after_i not in placed:
            continue
        need = dur_ms + rest_by_division.get(division_of[after_i], 0) * MIN_MS
        assert placed[after_i][1] >= placed[before_i][1] + need, (
            f"dependency violated: fixture {after_i} must start >= fixture {before_i} + {need}ms"
        )
        checked_deps += 1
    assert checked_deps == len(deps), "a dependency pair went unplaced — that arm would be vacuous"

    # per-division day cap. Bucketed by the board's own `day_index`, not by
    # re-deriving `start // DAY_MS` — the model groups by the caller's day and
    # re-deriving here would let a wrong day_index satisfy both sides at once.
    day_of_start = {start: day for _court, start, day in grid_slots}
    per_division_day = {}
    for fi, (_court, start) in placed.items():
        key = (division_of[fi], day_of_start[start])
        per_division_day[key] = per_division_day.get(key, 0) + 1
    for (division, day), count in per_division_day.items():
        assert count <= day_cap_by_division[division], (
            f"day cap violated: division {division} day {day} has {count} > "
            f"{day_cap_by_division[division]}"
        )


