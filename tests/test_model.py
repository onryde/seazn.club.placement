    grid_slots = [(0, _ROUND_DAY0_T0, 0), (1, _ROUND_DAY0_T0, 0), (0, _ROUND_DAY1_T0, 1)]
    fixtures = [([0, 1], 0)]
    existing = [(0, _ROUND_DAY0_T0)]  # round 2 pin, court 0, day 0
