#: The production budget from the design spec, and the wall the acceptance
#: criterion is stated at.
PRODUCTION_WALL_SECONDS = 8.0


def _load():
    """One-minute load average, for failure messages only.

    Every wall-clock claim in this service is load-sensitive — the same board
    measures ~4 940 ms/OPTIMAL on an idle box and 8 044 ms/FEASIBLE at load 11
    — so a red that does not say how busy the machine was cannot be triaged.
    Reported, never branched on: a test that skips itself under load is a test
    that never runs in CI.
    """
    return os.getloadavg()[0]


def _production_board():
    """The bench's `production_board()`, converted to the positional shape,
    PLUS the `rule_groups` its declared `rest_by_division`/`day_cap_by_
    division` now have to reach `build_model` through: `division_rules`
    (proto field 10), the wire path those dict keys used to be fed through,
    is retired (`placement.schema`'s module docstring). Without this, every
    caller below would silently solve an UNCAPPED, un-rested board -- a
    materially EASIER-to-place but HARDER-to-optimise problem (see
    `test_absent_day_cap_rule_means_no_cap`'s own docstring: the day cap is
    what pins fixtures across the lattice, and without it T1 does not finish
    inside a budget that used to be generous), not the same production board
    this file's tests are meant to be about.

    Returns an 8-tuple: the 7 `build_model(*board)`-shaped elements
    (`to_positional`'s own output) plus `rule_groups`.
    """
    # Module name follows the file the prompt's Step 2b names
    # (bench/placement_bench_boards.py) and its siblings placement_bench.py /
    # placement_repair_bench.py. bench/ reaches sys.path via `pythonpath` in
    # pyproject.toml — it is a script directory, not an installed package.
    from placement_bench_boards import production_board

    board = production_board()
    return (*to_positional(board), rule_groups_for(board))


def test_production_board_meets_the_stated_acceptance_criterion():
    """Prompt 02's acceptance criterion — RESTATED 2026-08-13, and the restating
    is the point of this docstring. Read it before treating the assertions
    below as the original ones.

    THE ORIGINAL CRITERION NO LONGER HOLDS AND IS NOT BEING QUIETLY DROPPED.
    It read: *"the production board solves to OPTIMAL with 35-37 assignments in
    under 8 seconds, verified by an automated test."* At four rungs that was
    true with ~40% margin (~4 940 ms idle). The day-aware T1 rungs took the
    chain to six, and measured over 6 runs at a wall that lets it finish, the
    full chain now costs 7 739 - 19 485 ms (median 17 657). At the 8 s
    production wall it therefore returns FEASIBLE with four of six rungs
    proved, not OPTIMAL.

    WHERE THE COST IS, because it is not where it looks. The three new rungs
    are cheap — `days` ~370 ms, `day_span` ~1 240 ms, `day_start` ~400 ms at
    the median. `idle_gap` went from a 1 348 ms median to 14 931 ms. The
    control run that explains it: `placed` + `idle_gap` alone, with no day
    rungs in the chain at all, costs 12 439 ms. So the retired whole-board
    `makespan` freeze had been doing `idle_gap`'s pruning for it as a side
    effect, and what the wall is paying for is the removal of that term — not
    the arrival of the new ones. `day_span` itself would not prove at all
    (still FEASIBLE at 180 s) until its redundant per-day floor was added; see
    `placement.model`'s T1 section.

    Owner ruling 2026-08-13, recorded rather than assumed: ship and report the
    numbers, the production wall is a separate decision. So this test asserts
    what the chain DOES now guarantee at 8 s, and says out loud what it no
    longer does. What it guarantees:

      * a COMPLETE board — every rung below `placed` only rearranges it;
      * the whole of T1 PROVED. Four rungs (`placed`, `days`, `day_span`,
        `day_start`) cost ~2.3 s at the median and have never exceeded 3.5 s in
        any measured run, so the day-aware objective — the part this change is
        for — finishes inside the production wall with margin. That is a
        stronger statement than the old `>= 1`.

    `test_objective.py::test_every_tier_completes_on_production_board` owns the
    six-rung claim, at a wall that lets it finish.

    THIS TEST IS LOAD-SENSITIVE ON PURPOSE and CI runs it advisory
    (`continue-on-error`) for that reason. The load average is reported in the
    failure message so a red can be triaged rather than guessed at; re-run
    alone before calling it a regression.
    """
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps, rule_groups = (
        _production_board()
    )
    model = build_model(
        fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps,
        rule_groups=rule_groups,
    )
    load = _load()
    outcome = solve(model, wall_seconds=PRODUCTION_WALL_SECONDS)
    detail = (
        f"status={outcome.status} placed={len(outcome.assignments)} "
        f"tiers_completed={outcome.tiers_completed} elapsed_ms={outcome.elapsed_ms} "
        f"wall={PRODUCTION_WALL_SECONDS}s load1={load:.2f} values={outcome.objective_values}"
    )
    assert 35 <= len(outcome.assignments) <= 37, detail
    # The wall is a cap, not a target.
    assert outcome.elapsed_ms <= PRODUCTION_WALL_SECONDS * 1000 + 250, detail
    # The whole day-aware objective proves inside the production wall.
    assert outcome.tiers_completed >= 4, detail
    reported = dict(outcome.objective_values)
    for tier in ("days", "day_span", "day_start"):
        assert tier in reported, detail


def test_production_board_solves_under_budget():
    """The board solves, completely, inside the production wall.

    Renamed from `..._solves_optimal_under_budget`, and the `status ==
    "OPTIMAL"` assertion is gone, because `solve()` no longer answers the
    question that assertion was asking. It was written when `solve()` was T0
    alone (~100 ms, always proved); it now drives the whole T0->T3 chain, whose
    final status reports whether all FOUR tiers were proved inside 8 s. That is
    a claim about the machine as much as the board — measured at 4 940 ms idle
    and past the wall under concurrent load — so it belongs in
    `test_objective.py`, which owns it and runs it deterministically.

    What is asserted here is what this test was always really about, and it is
    the assertion that carries the weight anyway: the board comes back whole.
    A missing objective returns OPTIMAL with ZERO placed, so the count is what
    catches that mutant, never the status.

    The 8 s wall here is inherited, not justified. An earlier version of this
    docstring claimed cutting it to 3 s let the participant-rest and court-gap
    mutants survive; that came from a single run per cell and does not
    reproduce — at six runs both mutants die MORE reliably at 3 s than at 8 s.
    The measured table is in
    `test_assignments_satisfy_every_stated_constraint`, and those two families
    are now guarded properly by `test_participant_rest_is_binding` and
    `test_the_court_turnaround_gap_is_binding`, on contended boards that do not
    depend on the wall at all.
    """
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps, rule_groups = (
        _production_board()
    )
    model = build_model(
        fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps,
        rule_groups=rule_groups,
    )
    outcome = solve(model, wall_seconds=8.0)
    assert outcome.status in ("OPTIMAL", "FEASIBLE")
    assert 35 <= len(outcome.assignments) <= 37
    assert outcome.tiers_completed >= 1
    assert outcome.elapsed_ms <= 8250


